#!/usr/bin/env python3
"""Generate the colour Stats tile with the repository's existing icon renderer."""
from pathlib import Path
from svg_to_lvgl import render_color, c_array
root = Path(__file__).resolve().parents[1]
data, w, h = render_color(str(root / 'assets/icons/stats.svg'), 128)
folder = root / 'src/gui/library'
(folder / 'stats_icon.h').write_text('#ifndef STATS_ICON_H\n#define STATS_ICON_H\n#include "lvgl/lvgl.h"\nextern const lv_image_dsc_t icon_menu_stats;\n#endif\n')
(folder / 'stats_icon.c').write_text('/* Generated by tools/gen_stats_icon.py from assets/icons/stats.svg. */\n#include "stats_icon.h"\nstatic const uint8_t pixels[] = {\n' + c_array(data) + '\n};\nconst lv_image_dsc_t icon_menu_stats = {\n.header = {.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_ARGB8888,.w=128,.h=128,.stride=512},\n.data_size=sizeof(pixels),.data=pixels\n};\n')
